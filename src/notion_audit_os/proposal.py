# ---------------------------------------------------------------------------
# Section builders
# ---------------------------------------------------------------------------


def _scope_summary(
    package: str,
    scorecard: M.Scorecard,
    fc: M.FindingsCollection,
) -> str:
    """Compose a grounded scope summary from structured audit inputs."""
    n = len(fc.findings)
    high_count = sum(
        1 for f in fc.findings if (f.severity or "") in ("critical", "high")
    )
    finding_phrase = f"{n} finding{'s' if n != 1 else ''}"
    if high_count:
        finding_phrase += f" ({high_count} high or critical severity)"

    return (
        f"Based on a Core Audit v1.1 overall score of {scorecard.overall_score} "
        f"({scorecard.maturity_band}), the recommended engagement is a {package}. "
        f"The audit identified {finding_phrase}. "
        f"This engagement is scoped to address the priority gaps confirmed in the "
        f"reviewed audit findings and is not expanded beyond the reviewed audit scope."
    )


# ---------------------------------------------------------------------------
# Top-level assembly
# ---------------------------------------------------------------------------


def assemble_proposal(
    audit_id: str,
    scorecard: M.Scorecard,
    fc: M.FindingsCollection,
) -> M.Proposal:
    """Assemble a structured :class:`models.Proposal` from approved inputs.

    ``recommended_package`` is taken directly from the scorecard. Deliverables
    and exclusions are drawn from the locked package-to-scope tables in this
    module. The scope summary is grounded in the audit score, band, and
    finding count \u2014 no content is invented.

    Args:
        audit_id: The audit identifier.
        scorecard: Validated scorecard artifact.
        fc: Approved findings collection.

    Returns:
        A validated :class:`models.Proposal` ready for serialization.
    """
    package = scorecard.recommended_package
    return M.Proposal(
        audit_id=audit_id,
        recommended_package=M.RecommendedPackage(package),
        scope_summary=_scope_summary(package, scorecard, fc),
        deliverables=list(PACKAGE_DELIVERABLES.get(package, [])),
        exclusions=list(PACKAGE_EXCLUSIONS.get(package, [])),
        generated_at=datetime.now(timezone.utc),
    )


# ---------------------------------------------------------------------------
# Markdown rendering
# ---------------------------------------------------------------------------


def render_proposal_markdown(proposal: M.Proposal) -> str:
    """Render a :class:`models.Proposal` as a Markdown string.

    Derived solely from the structured ``proposal`` object. No additional
    facts are introduced. Suitable for client review and later delivery.
    """
    generated = (
        proposal.generated_at.isoformat(timespec="seconds")
        if hasattr(proposal.generated_at, "isoformat")
        else str(proposal.generated_at)
    )
    lines: list[str] = [
        f"# Engagement Proposal \u2014 {proposal.audit_id}",
        "",
        f"_Generated: {generated}_",
        "",
        "---",
        "",
        "## Recommended Package",
        "",
        f"**{proposal.recommended_package}**",
        "",
        "---",
        "",
        "## Scope Summary",
        "",
        proposal.scope_summary,
        "",
        "---",
        "",
        "## Deliverables",
        "",
    ]
    if proposal.deliverables:
        for d in proposal.deliverables:
            lines.append(f"- {d}")
        lines.append("")
    else:
        lines += ["_(none specified)_", ""]

    lines += ["---", "", "## Exclusions", ""]
    if proposal.exclusions:
        for e in proposal.exclusions:
            lines.append(f"- {e}")
        lines.append("")
    else:
        lines += ["_(none specified)_", ""]

    return "\n".join(lines)


