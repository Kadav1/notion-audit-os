"""Proposal assembly for Core Audit v1.1.

Assembles a validated :class:`models.Proposal` from:

* a reviewed :class:`models.Scorecard`
* an approved :class:`models.FindingsCollection`

Deliverables and exclusions are drawn from the locked package-to-scope
tables in this module. They are not invented or generated by an LLM \u2014
the ``recommended_package`` from the scorecard is the anchor, and the
findings inform the scope summary sentence.

Locked decisions carried forward:

* ``recommended_package`` comes from the scorecard unchanged.
* Deliverables and exclusions are explicit, per-package, and not hallucinated.
* Scope summary is grounded in the audit score, band, and finding count.
* No scoring or routing logic lives here.
"""

from __future__ import annotations

from datetime import datetime, timezone

from . import models as M

# ---------------------------------------------------------------------------
# Locked package-to-scope tables
# ---------------------------------------------------------------------------

